/** A role's access from `ACTION:SCOPE` pairs, like a custom role built in the app. */
export function accessOf(code: string, pairs: string): MyAccess {
  return {
    membershipId: `m-${code.toLowerCase()}`,
    role: { code, name: code },
    permissions: pairs
      .split(',')
      .filter(Boolean)
      .map((pair) => {
        const [action, scope] = pair.split(':')
        return { action, scope: scope as Scope }
      }),
  }
}

